// 학생별 모의면접 결과를 저장하고(POST), 링크로 불러오는(GET) 서버 함수입니다.
// 여러 강사가 함께 쓰므로, 강사별로 결과 목록이 섞이지 않도록 t(강사 코드)로 키를 구분합니다.
// (자소서 첨삭 앱과 동일한 방식)

import Redis from 'ioredis';

let redis;
function getRedis() {
  if (!redis) {
    redis = new Redis(process.env.REDIS_URL);
  }
  return redis;
}

function generateId() {
  return 'res_' + Date.now().toString(36) + '_' + Math.random().toString(36).slice(2, 8);
}

function safeTeacherId(raw) {
  return String(raw || '').trim().toLowerCase().replace(/[^a-z0-9가-힣_-]/g, '').slice(0, 40);
}

function slugPart(s) {
  return String(s || '').trim().toLowerCase().replace(/[^a-z0-9가-힣]+/g, '-').slice(0, 40);
}

// 결과가 만들어질 때마다(즉시모드·검토모드 모두), 강사가 설정해둔 "현재 특강 기관명·전공(대상)"을 기준으로
// "수강생 사후관리 트래커"의 진로모아관리 통계(기관·전공별 인원수)에 자동으로 인원을 1명 누적함.
// 답변 내용은 저장하지 않고 인원수·기관명·전공명만 집계됨. 기관명을 설정 안 해뒀으면 조용히 건너뜀.
async function upsertTrackerStat(client, t, orgName, field) {
  try {
    if (!orgName) return;
    const safeField = field || '(전공 미지정)';
    const id = `auto_interview_${slugPart(orgName)}_${slugPart(safeField)}`;
    const itemKey = `tracker_program:${t}:${id}`;
    const indexKey = `tracker_programs_index:${t}`;
    const now = new Date().toISOString();
    const raw = await client.get(itemKey);
    const record = raw ? JSON.parse(raw) : {
      id, orgName, field: safeField, programName: '모의면접 시뮬레이터 (자동집계)',
      date: now.slice(0, 10), participantCount: 0, renewalIntent: '미정',
      feedbackNotes: '', proposalNotes: '', avgSatisfaction: '', autoGenerated: true,
      createdAt: now
    };
    record.participantCount = (parseInt(record.participantCount, 10) || 0) + 1;
    record.updatedAt = now;
    await client.set(itemKey, JSON.stringify(record));
    await client.hset(indexKey, id, JSON.stringify({
      id: record.id, orgName: record.orgName, programName: record.programName,
      date: record.date, participantCount: record.participantCount, avgSatisfaction: record.avgSatisfaction
    }));
  } catch (err) {
    console.error('트래커 통계 자동 반영 실패:', err);
  }
}

// 강사 검토 승인이 끝났을 때만(record.notify === true) 학생에게 결과 링크를 이메일로 보냄.
// 즉시모드(학생이 직접 링크를 만드는 경우)는 화면에 바로 링크가 뜨므로 중복 발송하지 않음.
// RESEND_API_KEY가 없거나 이메일을 안 남겼으면 조용히 건너뜀 (알림은 부가기능이라 실패해도 저장 자체는 막지 않음).
async function notifyStudentByEmail(t, id, record, host) {
  try {
    if (!process.env.RESEND_API_KEY) { console.error('학생 알림 건너뜀: RESEND_API_KEY 없음'); return; }
    if (!record.notify) { console.log('학생 알림 건너뜀: notify=false'); return; }
    const to = record.studentEmail;
    if (!to) { console.log('학생 알림 건너뜀: studentEmail 없음'); return; }
    const link = `https://${host}/?t=${encodeURIComponent(t)}#result=${id}`;
    const res = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${process.env.RESEND_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        from: 'MOA FORMULA <moaformula@jinromoa.co.kr>',
        to: [to],
        subject: `[모의면접] ${record.studentName || '학생'}님의 결과가 도착했어요`,
        text: `${record.studentName || '학생'}님, 요청하신 모의면접 검토 결과가 준비됐어요.\n\n아래 링크에서 확인해 주세요.\n${link}`
      })
    });
    if (!res.ok) {
      const body = await res.text();
      console.error('Resend 발송 실패(학생):', res.status, body);
    } else {
      console.log('Resend 발송 성공(학생):', to);
    }
  } catch (err) {
    console.error('학생 알림 메일 발송 실패:', err);
  }
}

// 모의면접 결과가 만들어질 때, 그 학생의 이메일이 "수강생 사후관리 트래커"의 개인관리에
// 이미 등록된 학생 카드와 일치할 때만, 오늘 날짜로 상담 이력에 한 줄 자동 기록함.
// 등록된 카드가 없으면(집체교육 등 일회성 참여자) 아무 것도 하지 않음 — 새 카드를 자동으로 만들지 않음.
// 같은 학생이 하루에 여러 번 이용해도 그날짜 한 줄에 건수만 합쳐서 표시됨.
async function upsertStudentConsultLog(client, t, studentEmail, kind) {
  try {
    const email = String(studentEmail || '').trim().toLowerCase();
    if (!email) return false;
    const indexKey = `tracker_students_index:${t}`;
    const hash = await client.hgetall(indexKey);
    let matchId = null;
    for (const [id, raw] of Object.entries(hash || {})) {
      try {
        const summary = JSON.parse(raw);
        if ((summary.email || '').trim().toLowerCase() === email) { matchId = id; break; }
      } catch (e) { /* 손상된 항목은 건너뜀 */ }
    }
    if (!matchId) return false;

    const itemKey = `tracker_student:${t}:${matchId}`;
    const raw = await client.get(itemKey);
    if (!raw) return false;
    const record = JSON.parse(raw);
    record.consultLog = record.consultLog || [];
    const today = new Date().toISOString().slice(0, 10);
    let todayEntry = record.consultLog.find(c => c.date === today && c.autoCounts);
    if (!todayEntry) {
      todayEntry = { date: today, memo: '', autoCounts: {}, auto: true };
      record.consultLog.push(todayEntry);
    }
    todayEntry.autoCounts[kind] = (todayEntry.autoCounts[kind] || 0) + 1;
    const labels = { resume: '자소서 첨삭', interview: '모의면접' };
    todayEntry.memo = Object.entries(todayEntry.autoCounts)
      .map(([k, n]) => `${labels[k] || k} ${n}건`)
      .join(' · ') + ' 완료 (자동 기록)';
    await client.set(itemKey, JSON.stringify(record));
    return true;
  } catch (err) {
    console.error('학생 상담이력 자동기록 실패:', err);
    return false;
  }
}

export default async function handler(req, res) {
  const client = getRedis();
  const t = safeTeacherId(req.query.t);
  if (!t) return res.status(400).json({ error: 't(강사 코드) 파라미터가 필요합니다.' });

  const indexKey = `interview_results_index:${t}`;
  const itemKey = (id) => `interview_result:${t}:${id}`;

  if (req.method === 'POST') {
    const record = req.body;
    if (!record || !record.items) {
      return res.status(400).json({ error: '저장할 결과 데이터가 없습니다.' });
    }
    try {
      const id = generateId();

      // 트래커 연동 정보를 먼저 계산해서 record에 포함 — 학생 결과 화면에서 만족도 설문 링크를 바로 만들 수 있게 함
      // 학생이 직접 소속 기관·전공을 선택했으면(여러 기관 동시 운영) 그 값을 우선 쓰고, 없으면 강사가 설정해둔 단일 값을 씀
      let institutionNameForSurvey = null;
      let targetFieldForSurvey = null;
      let groupCodeExpiryDays = 5;
      try {
        const configRaw = await client.get(`interview_app_config:${t}`);
        const config = configRaw ? JSON.parse(configRaw) : null;
        const orgName = (record.studentInstitution && record.studentInstitution.trim()) || (config && config.institutionName) || null;
        const field = (record.studentTargetField && record.studentTargetField.trim()) || (config && config.targetField) || null;
        if (orgName) {
          institutionNameForSurvey = orgName;
          targetFieldForSurvey = field;
          record.trackerProgramId = `auto_interview_${slugPart(orgName)}_${slugPart(field || '(전공 미지정)')}`;
        }
        if (config && config.groupCodeExpiryDays) groupCodeExpiryDays = parseInt(config.groupCodeExpiryDays, 10) || 5;
      } catch (err) {
        console.error('트래커 연동용 설정 조회 실패:', err);
      }

      // 트래커의 개인관리 카드와 이메일이 일치하는 "1:1 코칭" 학생은 기간 제한 없음.
      // 일치하지 않는(집체교육·일회성) 학생은 강사가 설정한 일수 후 결과 링크가 막힘 (당일 포함으로 계산).
      const isIndividualCoaching = await upsertStudentConsultLog(client, t, record.studentEmail, 'interview');
      if (!isIndividualCoaching) {
        const now = new Date();
        record.expiresAt = new Date(now.getFullYear(), now.getMonth(), now.getDate() + groupCodeExpiryDays).getTime();
      }

      await client.set(itemKey(id), JSON.stringify(record));
      const meta = JSON.stringify({
        id,
        studentName: record.studentName,
        category: record.category,
        createdAt: record.createdAt,
        expiresAt: record.expiresAt || null
      });
      await client.lpush(indexKey, meta);
      await client.ltrim(indexKey, 0, 499); // 최근 500건까지만 보관
      await notifyStudentByEmail(t, id, record, req.headers.host); // 서버리스 환경에서는 응답 전에 완료를 기다려야 중간에 끊기지 않음

      if (institutionNameForSurvey) {
        upsertTrackerStat(client, t, institutionNameForSurvey, targetFieldForSurvey);
      }

      return res.status(200).json({ id });
    } catch (err) {
      console.error(err);
      return res.status(500).json({ error: '결과 저장 중 오류가 발생했습니다.' });
    }
  }

  if (req.method === 'GET') {
    const { id, list } = req.query;

    if (list === '1') {
      try {
        const raw = await client.lrange(indexKey, 0, 199);
        const items = raw.map((r) => JSON.parse(r));
        return res.status(200).json({ items });
      } catch (err) {
        console.error(err);
        return res.status(500).json({ error: '목록 조회 중 오류가 발생했습니다.' });
      }
    }

    if (!id) {
      return res.status(400).json({ error: 'id가 필요합니다.' });
    }
    try {
      const value = await client.get(itemKey(id));
      if (!value) {
        return res.status(404).json({ error: '결과를 찾을 수 없습니다.' });
      }
      const record = JSON.parse(value);
      if (req.query.admin !== '1' && record.expiresAt && Date.now() > record.expiresAt) {
        return res.status(410).json({ error: '조회 가능한 기간이 지났어요. 결과가 필요하시면 강사님께 문의해 주세요.', expired: true });
      }
      return res.status(200).json({ record });
    } catch (err) {
      console.error(err);
      return res.status(500).json({ error: '결과 조회 중 오류가 발생했습니다.' });
    }
  }

  return res.status(405).json({ error: '허용되지 않는 요청입니다.' });
}
